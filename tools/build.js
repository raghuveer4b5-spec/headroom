#!/usr/bin/env node
// Bundles src/ (CommonJS) into one browser script that defines globalThis.Headroom.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const OUT = path.join(ROOT, 'skills', 'readiness', 'scripts', 'headroom-garmin.js');

const modules = new Map();

function resolve(fromId, request) {
  const id = path.posix.normalize(path.posix.join(path.posix.dirname(fromId), request));
  return id.endsWith('.js') ? id : `${id}.js`;
}

function collect(id) {
  if (modules.has(id)) return;
  let code = fs.readFileSync(path.join(SRC, id), 'utf8');
  modules.set(id, null);
  code = code.replace(/require\('(\.[^']+)'\)/g, (_, req) => {
    const dep = resolve(id, req);
    collect(dep);
    return `__req('${dep}')`;
  });
  modules.set(id, code);
}

collect('runner.js');

const defs = [...modules.entries()]
  .map(([id, code]) => `'${id}': function (module, exports, __req) {\n${code}\n}`)
  .join(',\n');

// Light minification: the agent pastes this file into the page on every run, so size is token cost.
function compact(code) {
  return code
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('//'))
    .join('\n');
}

const bundle = `// Generated by tools/build.js from src/. Do not edit by hand.
` + compact(`(function () {
const defs = {
${defs}
};
const cache = {};
function __req(id) {
  if (cache[id]) return cache[id].exports;
  const module = { exports: {} };
  cache[id] = module;
  defs[id](module, module.exports, __req);
  return module.exports;
}
globalThis.Headroom = __req('runner.js');
})();
`) + '\n';

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, bundle);
console.log(`Wrote ${path.relative(ROOT, OUT)} (${bundle.length} bytes, ${modules.size} modules)`);
